#!/usr/bin/env python3
"""Generate correctly rounded binary64 powers from TC-ALLOWANCE mathematics."""
import argparse
from fractions import Fraction
import hashlib
import math
from pathlib import Path
import struct

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--spec',type=Path,default=Path('/home/legolas/king-spec'))
p.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'src/time_powers.rs')
a=p.parse_args()
source=a.spec/'spec/time-allowance.md'
base=Fraction.from_float(0.966667)
lines=['// Generated by tools/generate_time_powers.py from TC-ALLOWANCE mathematics.',
       '// Normative document SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
       '// Nearest-even binary64 of the exact binary64 base raised to j=1..99.',
       '// Generation verifies each exact rational against adjacent-float midpoints.',
       'pub const POWERS: [f64; 99] = [']
for j in range(1,100):
    exact=base**j
    rounded=float(exact)
    bits=struct.unpack('>Q',struct.pack('>d',rounded))[0]
    value=Fraction.from_float(rounded)
    lo=(Fraction.from_float(math.nextafter(rounded,-math.inf))+value)/2
    hi=(Fraction.from_float(math.nextafter(rounded,math.inf))+value)/2
    assert lo<=exact<=hi
    assert exact not in (lo,hi) or bits%2==0
    lines.append(f'    f64::from_bits(0x{bits:016x}), // j={j}')
lines.append('];')
a.output.write_text('\n'.join(lines)+'\n')
print('Generated 99 verified rounded powers; no fixture data used.')
