#!/usr/bin/env python3
"""Generate numeric square bases from normative spec data, never fixture answers."""
import argparse
import hashlib
import json
from pathlib import Path

p = argparse.ArgumentParser(description=__doc__)
p.add_argument("--spec", type=Path, default=Path("/home/legolas/king-spec"))
p.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "src/eval_basis.rs")
args = p.parse_args()
source = args.spec / "spec/positional-value-basis.json"
raw = source.read_bytes()
data = json.loads(raw)
assert data["version"] == 1
assert data["orientation"] == {"rows": "rank8-to-rank1", "columns": "fileA-to-fileH", "side": "white"}
phases = ("opening", "middlegame", "endgame")
kinds = ("pawn", "knight", "bishop", "rook", "queen", "king")
lines = ["// Generated by tools/generate_spec_tables.py from normative positional-value-basis.json.",
         "// Source SHA256: " + hashlib.sha256(raw).hexdigest(),
         "// White orientation, a1=0; phases O/M/E; types P/N/B/R/Q/K.",
         "pub const SQUARE_BASIS: [[[i16; 64]; 6]; 3] = ["]
for phase in phases:
    lines.append("    [ // " + phase)
    for kind in kinds:
        rows = data["values"][phase][kind]
        assert len(rows) == 8 and all(len(row) == 8 for row in rows)
        assert all(type(n) is int and -32768 <= n <= 32767 for row in rows for n in row)
        lines.append("        [ // " + kind)
        for row in reversed(rows):
            lines.append("            " + ", ".join(map(str, row)) + ",")
        lines.append("        ],")
    lines.append("    ],")
lines.append("];")
args.output.write_text("\n".join(lines) + "\n")
print(json.dumps({"source": str(source), "source_sha256": hashlib.sha256(raw).hexdigest(),
                  "output": str(args.output), "fixture_data_used": False}))
